"""既にある課題を、いまの採点基準に合わせて書き直す（#306）。

## なぜ要るか

既存の課題は**入出力しか見ない前提**で書かれている。仕様が曖昧なまま、
例と本文が食い違ったまま、読みやすさのような観点への配慮が無いまま出題され
ている ── そこへコースの共通ルーブリックが「読みやすさ 0.3」と言っても、
**問題文がそれを求めていない**ので学習者には理由が分からない。

1 問ずつ手で直すには数が多い。**現在の基準に合わせた新しい版を作らせ、教員は
差分を読んで承認する。**

## モデルにさせること・させないこと

**させるのは、読まなければ分からないことだけである。**

    問題文の書き直し   仕様の曖昧さ、例と本文の食い違い、求める観点の明示
    何を直したか       差分を読む教員の手掛かり（P4 の「根拠」にあたる）
    知識要素の候補     問題文が実際に問うているもの

**させないのは、決まっていることである。** 観点（ルーブリック）はコースの
共通ルーブリックが持っており、段階の記述まで含めて既に決まっている ── そこを
モデルに書かせると、コースごとに違う段階が課題ごとにも割れる。段階の設計は
教員の仕事で、生成の対象ではない（設計原則 P5）。

**題名も変えない。** 同じ課題の改訂であって別の課題ではない ── 題名が変わると
一覧で別物に見え、学習者は「前に見た問題が消えた」と読む。
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field

__all__ = ["RevisedTask"]


class RevisedTask(BaseModel):
    """モデルに返させる構造化出力（設計原則 P4）。"""

    model_config = ConfigDict(extra="ignore")

    statement: str = Field(min_length=1, max_length=8000)
    #: 何を直したか。**箇条書き 1 行 1 件。** 差分を読む教員の手掛かりで、
    #: これが書けない改訂は直すところが無かったということである。
    changes: tuple[str, ...] = Field(default=(), max_length=20)
    #: この課題が問う知識要素（正準キー）。**登録済みの語彙から選ばせる** ──
    #: 新しい知識要素は作れない（#299）。呼び出し側が照合して落とす。
    knowledge_components: tuple[str, ...] = Field(default=(), max_length=20)
