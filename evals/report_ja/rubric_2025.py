def load_human(path):
    """採点表を {学籍番号: {観点コード: 段階}} に読む。"""
    import csv

    out = {}
    with open(path, encoding="utf-8-sig", newline="") as fh:
        for row in csv.DictReader(fh):
            login = row["学籍番号"].strip().upper()
            out[login] = {code: int(row[column]) for code, column in _CSV_COLUMN.items()}
    return out


