def _levels(items: list[tuple[int, str, str]], top: int) -> list[dict]:
    return [
        {
            "level": level,
            "label": label,
            "descriptor": descriptor,
            "score_ratio": level / top,
        }
        for level, label, descriptor in items
    ]


