def load_human(path):
    """採点表を {学籍番号: {観点コード: 段階}} に読む。

    比率（0.1〜1.0）を 10 倍して段階にする。**点が入っていない行は
    未提出なので落とす**（0 点として混ぜると、採点者が 0 を付けたことになる）。
    """
    import csv

    out = {}
    with open(path, encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.reader(fh))
    header = rows[1]
    position = {name: header.index(name) for name in _CSV_COLUMN.values()}
    login_at = header.index("学籍番号")
    for row in rows[2:]:
        if len(row) <= max(position.values()):
            continue
        cells = {code: row[position[name]].strip() for code, name in _CSV_COLUMN.items()}
        if not all(cells.values()):
            continue  # 未提出、または未採点
        out[row[login_at].strip().upper()] = {
            code: round(float(value) * 10) for code, value in cells.items()
        }
    return out
